# 1 / 14 - Bitwise operators
print (5 >> 4)  # Right Shift       0
print (5 << 1  )# Left Shift        10
print (8 & 5 )  # Bitwise AND       0
print (9 | 4)   # Bitwise OR        13
print (12 ^ 42 )# Bitwise XOR       38
print (~88  )   # Bitwise NOT       -89


